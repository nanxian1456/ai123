CREATE TABLE user_profiles (
    owner_id VARCHAR(128) PRIMARY KEY,
    nickname VARCHAR(30) NOT NULL DEFAULT '',
    organization VARCHAR(100) NOT NULL DEFAULT '',
    position VARCHAR(100) NOT NULL DEFAULT '',
    city VARCHAR(100) NOT NULL DEFAULT '',
    bio VARCHAR(500) NOT NULL DEFAULT '',
    avatar_type VARCHAR(20) NOT NULL DEFAULT 'male-1',
    avatar_url VARCHAR(500) DEFAULT '',
    contact_code VARCHAR(12) UNIQUE,
    avatar_visible BOOLEAN NOT NULL DEFAULT FALSE,
    nickname_visible BOOLEAN NOT NULL DEFAULT FALSE,
    organization_visible BOOLEAN NOT NULL DEFAULT FALSE,
    position_visible BOOLEAN NOT NULL DEFAULT FALSE,
    city_visible BOOLEAN NOT NULL DEFAULT FALSE,
    bio_visible BOOLEAN NOT NULL DEFAULT FALSE,
    profile_completed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE published_profiles (
    owner_id VARCHAR(128) PRIMARY KEY,
    nickname VARCHAR(30) NOT NULL DEFAULT '',
    organization VARCHAR(100) NOT NULL DEFAULT '',
    position VARCHAR(100) NOT NULL DEFAULT '',
    city VARCHAR(100) NOT NULL DEFAULT '',
    bio VARCHAR(500) NOT NULL DEFAULT ''
);

CREATE TABLE contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id VARCHAR(128) NOT NULL,
    name VARCHAR(50) NOT NULL,
    organization VARCHAR(100) NOT NULL DEFAULT '',
    position VARCHAR(50) NOT NULL DEFAULT '',
    city VARCHAR(50) NOT NULL DEFAULT '',
    province VARCHAR(50) NOT NULL DEFAULT '',
    phone VARCHAR(30) NOT NULL DEFAULT '',
    email VARCHAR(100) NOT NULL DEFAULT '',
    note VARCHAR(500) NOT NULL DEFAULT ''
);
CREATE INDEX idx_contacts_owner ON contacts(owner_id);
CREATE INDEX idx_contacts_owner_city ON contacts(owner_id, city);

CREATE TABLE contact_tags (
    contact_id BIGINT NOT NULL REFERENCES contacts(id),
    tag_order INTEGER NOT NULL,
    tag VARCHAR(20) NOT NULL,
    PRIMARY KEY (contact_id, tag_order)
);

CREATE TABLE relationships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id VARCHAR(128) NOT NULL,
    source_id BIGINT NOT NULL REFERENCES contacts(id),
    target_id BIGINT NOT NULL REFERENCES contacts(id),
    type VARCHAR(30) NOT NULL,
    note VARCHAR(200) NOT NULL DEFAULT ''
);
CREATE INDEX idx_relationships_owner ON relationships(owner_id);
CREATE INDEX idx_relationships_source ON relationships(owner_id, source_id);
CREATE INDEX idx_relationships_target ON relationships(owner_id, target_id);
